import {test,expect} from '@playwright/test';
import {readFileSync} from 'node:fs';
test('quote to supply to invoice posts accounting without opening the accounting screen',async({page})=>{
 test.skip(!process.env.KARMA_E2E_CREDENTIALS,'Requires a disposable database; see platform test instructions');
 const fixture=JSON.parse(readFileSync(process.env.KARMA_E2E_CREDENTIALS!,'utf8'));
 await page.goto('/');await expect(page.locator('.product-card').first()).toBeVisible();
 await page.getByRole('button',{name:/ورود به فضای کارکنان/}).click();
 await page.getByLabel('نام کاربری').fill(fixture.username);await page.getByLabel('رمز عبور',{exact:true}).fill(fixture.password);
 await page.getByRole('button',{name:'ورود امن'}).click();
 await expect(page.locator('.profile')).toContainText(fixture.username);
 await page.getByRole('textbox',{name:'جستجوی محصول'}).fill('KR-100001');
 await expect(page.locator('.tech-code').first()).toContainText('DIN912-M3X25-8.8-ZN');
 await page.locator('.product-card').first().getByRole('button',{name:/انتخاب/}).click();
 await page.getByRole('button',{name:'فروش و خرید'}).click();
 await page.getByRole('button',{name:/ثبت جدید/}).click();
 await page.getByLabel('انتخاب مشتری').selectOption(String(fixture.party));
 await page.getByLabel('قیمت واحد (ریال)',{exact:true}).fill('100000');
 await page.getByRole('button',{name:'ذخیرهٔ پیش‌نویس',exact:true}).click();
 await page.locator('tbody tr').first().getByRole('button',{name:'جزئیات'}).click();
 await page.getByRole('button',{name:'صدور سند',exact:true}).click();
 await page.getByRole('button',{name:'تأیید پیش‌فاکتور',exact:true}).click();
 await page.getByRole('button',{name:'ساخت برگهٔ تأمین',exact:true}).click();
 await page.getByLabel('مقدار تأمین‌شده').fill('1');await page.getByLabel('منبع تأمین').fill('منبع آزمون');
 await page.getByLabel('تأمین همهٔ ردیف‌ها تکمیل شده است').check();
 await page.getByRole('button',{name:'ثبت پیشرفت تأمین',exact:true}).click();
 await page.getByRole('button',{name:'ساخت فاکتور فروش',exact:true}).click();
 const issued=page.waitForResponse(res=>res.url().endsWith('/issue/')&&res.request().method()==='POST');
 await page.getByRole('button',{name:'صدور سند',exact:true}).click();
 const invoice=await (await issued).json();expect(invoice.kind).toBe('invoice');expect(invoice.status).toBe('issued');
 await expect.poll(async()=>{const r=await page.request.get(`/api/v1/documents/${invoice.id}/`);return (await r.json()).accounting_status},{timeout:20000}).toBe('posted');
 const pdf=await page.request.get(`/api/v1/documents/${invoice.id}/pdf/`);expect(pdf.status()).toBe(200);expect((await pdf.body()).subarray(0,5).toString()).toBe("%PDF-");
 const forbidden=await page.request.get(`/api/v1/ledger/?unit=${fixture.unit}`);expect(forbidden.status()).toBe(403);
});
